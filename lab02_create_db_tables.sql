       (N'Україна', N'Львів', N'вул. Стрийська, 350',        200.00),
       (N'Україна', N'Одеса', N'вул. Фонтанська дорога, 12',  95.75);
GO

-- ---------------------------------------------------------------------
-- 3. Друга таблиця — вид військ (створена в командному рядку)
--    sqlcmd -S localhost -E -d SQLLAB
--    Атрибути: назва
-- ---------------------------------------------------------------------
CREATE TABLE dbo.MilitaryTypes (
    ID   INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL
);
GO

