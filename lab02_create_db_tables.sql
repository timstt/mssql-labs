   Варіант 3 — Інформаційна система військового округу

   За завданням:
     - БД створюється в графічному дизайнері SSMS;
     - перша таблиця (Locations — місця дислокації) створюється в SSMS;
     - друга таблиця (MilitaryTypes — вид військ) створюється
       в командному рядку (sqlcmd);
     - у першу таблицю додаємо 3 рядки, у другу — 5.
   Нижче наведено T-SQL, еквівалентний діям у графічному дизайнері.
   ===================================================================== */

-- ---------------------------------------------------------------------
-- 1. Створення бази даних
--    (у SSMS: Databases -> New Database... -> SQLLAB)
-- ---------------------------------------------------------------------
IF DB_ID(N'SQLLAB') IS NULL
    CREATE DATABASE SQLLAB;
GO

USE SQLLAB;
GO

-- ---------------------------------------------------------------------
-- 2. Перша таблиця — місця дислокації (створена в SSMS: Tables -> New -> Table)
--    Атрибути: країна, місто, адреса, площа
-- ---------------------------------------------------------------------
CREATE TABLE dbo.Locations (
    Id      INT IDENTITY(1,1) PRIMARY KEY,
    Country NVARCHAR(50)  NOT NULL,
    City    NVARCHAR(50)  NOT NULL,
    Address NVARCHAR(100) NOT NULL,
    Area    DECIMAL(10,2) NOT NULL          -- площа, яку займає
);
GO

-- 3 рядки (у SSMS вносились через Edit Top 200 Rows)
